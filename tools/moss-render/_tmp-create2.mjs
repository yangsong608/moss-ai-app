import puppeteer from 'puppeteer-core'
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox', '--disable-gpu'] })
const page = await browser.newPage()
await page.setViewport({ width: 390, height: 844 })
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
await page.goto('http://localhost:5180/#/pages/notes/notes', { waitUntil: 'networkidle0', timeout: 60000 })
await sleep(1400)
await page.click('.head-new')
await sleep(400)
await page.evaluate(() => Array.from(document.querySelectorAll('.cs-nb')).find((n) => n.textContent.includes('新笔记本'))?.click())
await sleep(300)
const input = await page.$('.cs-input input')
await input.click()
await page.keyboard.type('灵感', { delay: 120 })
await sleep(500)
console.log('input value:', await page.$eval('.cs-input input', (el) => el.value))
await page.evaluate(() => Array.from(document.querySelectorAll('.cs-actions .btn')).find((n) => n.textContent.includes('创建并编辑'))?.click())
await sleep(500)
console.log('saved notebook:', await page.evaluate(() => JSON.parse(localStorage.getItem('moss.work.dev-a')).notes[0].notebook))
await browser.close()
